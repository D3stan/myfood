-- Applied at start-up; every statement is idempotent.
PRAGMA journal_mode = WAL;
PRAGMA foreign_keys = ON;

CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  emoji TEXT NOT NULL,
  code_hash TEXT NOT NULL UNIQUE,   -- sha256 hex of the access code
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  created_at INTEGER NOT NULL,
  last_seen_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS items (
  id INTEGER PRIMARY KEY,
  name TEXT NOT NULL,
  name_key TEXT NOT NULL UNIQUE,    -- nameKey(name) from src/shared/text.ts
  emoji TEXT NOT NULL,
  category TEXT NOT NULL,
  unit TEXT NOT NULL,
  step REAL NOT NULL,
  pack_size REAL NOT NULL,
  low_at REAL,
  archived_at INTEGER,
  created_at INTEGER NOT NULL
);

-- aliasKey(receipt line) -> item, learned when a receipt is confirmed.
CREATE TABLE IF NOT EXISTS aliases (
  text TEXT PRIMARY KEY,
  item_id INTEGER NOT NULL REFERENCES items(id)
);

CREATE TABLE IF NOT EXISTS events (
  cid TEXT PRIMARY KEY,             -- generated by the client (or the server for AI jobs)
  seq INTEGER NOT NULL UNIQUE,      -- insertion order; breaks ties on `at`
  user_id INTEGER NOT NULL REFERENCES users(id),
  at INTEGER NOT NULL,              -- unix ms
  kind TEXT NOT NULL,               -- buy | eat | adjust
  source TEXT NOT NULL,             -- manual | preset | ai | receipt
  note TEXT,
  preset_id INTEGER,
  job_id INTEGER,
  undone_at INTEGER
);
CREATE INDEX IF NOT EXISTS events_at ON events(at, seq);

-- See src/shared/stock.ts for how these become stock.
CREATE TABLE IF NOT EXISTS event_lines (
  event_cid TEXT NOT NULL REFERENCES events(cid) ON DELETE CASCADE,
  item_id INTEGER NOT NULL REFERENCES items(id),
  qty REAL NOT NULL,                -- signed delta, or the absolute amount when is_set = 1
  is_set INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS event_lines_event ON event_lines(event_cid);

CREATE TABLE IF NOT EXISTS presets (
  id INTEGER PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  name TEXT NOT NULL,
  emoji TEXT NOT NULL,
  hour REAL NOT NULL
);

CREATE TABLE IF NOT EXISTS preset_lines (
  preset_id INTEGER NOT NULL REFERENCES presets(id) ON DELETE CASCADE,
  item_id INTEGER NOT NULL REFERENCES items(id),
  qty REAL NOT NULL,
  PRIMARY KEY (preset_id, item_id)
);

CREATE TABLE IF NOT EXISTS jobs (
  id INTEGER PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id),
  text TEXT NOT NULL,
  images TEXT NOT NULL DEFAULT '[]',     -- JSON array of file names inside the job folder
  status TEXT NOT NULL,                  -- queued | running | review | done | failed
  result TEXT,                           -- JSON AiResult
  error TEXT,
  event_cids TEXT NOT NULL DEFAULT '[]', -- JSON array
  created_at INTEGER NOT NULL,
  finished_at INTEGER,
  dismissed_at INTEGER
);

CREATE TABLE IF NOT EXISTS meta (key TEXT PRIMARY KEY, value TEXT NOT NULL);
INSERT OR IGNORE INTO meta(key, value) VALUES ('rev', '0');
